// Rebuilds the column lists in lib/ai/data-guide.md from the database (every
// migration applied to a local PGlite, no live connection), then writes
// lib/ai/dataGuide.ts, the copy the server sends to the model.
//
//   npm run ai:guide
//
// Fails if a view has no section in the guide, or a section names no view.

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { migratedDb } from "../lib/ai/testing/migratedDb";

const GUIDE = join(process.cwd(), "lib", "ai", "data-guide.md");
const OUT = join(process.cwd(), "lib", "ai", "dataGuide.ts");

async function main() {
  const db = await migratedDb();
  const { rows } = await db.query<{ view: string; cols: string }>(`
    select c.table_name as view,
           string_agg(c.column_name || ' (' || case when c.data_type = 'ARRAY' then trim(leading '_' from c.udt_name) || '[]'
                                               when c.data_type = 'USER-DEFINED' then c.udt_name
                                               else c.data_type end || ')', ', ' order by c.ordinal_position) as cols
    from information_schema.columns c
    join information_schema.views v on v.table_schema = c.table_schema and v.table_name = c.table_name
    where c.table_schema = 'ai'
    group by c.table_name`);
  await db.close();
  const columns = new Map(rows.map((r) => [r.view, r.cols]));

  let md = readFileSync(GUIDE, "utf8").replace(/\r\n/g, "\n");
  const seen = new Set<string>();
  md = md.replace(
    /^### (\S+)\n([\s\S]*?)<!-- columns -->\n[\s\S]*?<!-- \/columns -->/gm,
    (_m, name: string, notes: string) => {
      const cols = columns.get(name);
      if (!cols) throw new Error(`data-guide.md has a section for "${name}", which is not a view in schema ai.`);
      seen.add(name);
      return `### ${name}\n${notes}<!-- columns -->\nColumns: ${cols}\n<!-- /columns -->`;
    },
  );
  const missing = [...columns.keys()].filter((v) => !seen.has(v)).sort();
  if (missing.length) throw new Error(`data-guide.md has no section for: ${missing.join(", ")}`);

  writeFileSync(GUIDE, md);
  writeFileSync(
    OUT,
    `// Generated by scripts/ai-data-guide.ts from data-guide.md. Do not edit; run npm run ai:guide.\n\nexport const DATA_GUIDE = ${JSON.stringify(md)};\n`,
  );
  console.log(`Wrote ${columns.size} views to lib/ai/data-guide.md and lib/ai/dataGuide.ts`);
}

main().catch((e) => {
  console.error(e instanceof Error ? e.message : e);
  process.exit(1);
});
